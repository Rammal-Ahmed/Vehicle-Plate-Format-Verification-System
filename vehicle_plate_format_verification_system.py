numplate = input("Enter your Number Plate : ").strip().upper()
if numplate[:3].isalpha() == True and numplate[:2].isupper() == True and numplate[3] == "-" and numplate[4:].isdigit() and len(numplate) == 7:
  print()
  print("This Vehicle license Plate is Valid.!!")
else:
  print()
  print("Format is Invalid ")